create extension if not exists "pgcrypto";

-- ---------- TABLES ----------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  name        text,
  phone       text,
  address     text,
  is_admin    boolean not null default false,   -- only the shop owner is true
  created_at  timestamptz not null default now()
);

create table if not exists public.products (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  category    text not null,
  price       numeric(10,2) not null check (price >= 0),
  image_url   text,
  description text,
  created_at  timestamptz not null default now()
);

-- v2 columns on products
alter table public.products add column if not exists stock  integer not null default 0 check (stock >= 0);
alter table public.products add column if not exists status text    not null default 'active';
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'products_status_check') then
    alter table public.products add constraint products_status_check check (status in ('active','draft','inactive'));
  end if;
end $$;

create table if not exists public.wishlist (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles(id) on delete cascade,
  product_id  uuid not null references public.products(id) on delete cascade,
  created_at  timestamptz not null default now(),
  unique (user_id, product_id)
);

-- orders: items are copied into the order (jsonb) so invoices never change later
create table if not exists public.orders (
  id             uuid primary key default gen_random_uuid(),
  order_no       bigint generated by default as identity (start with 1001),
  user_id        uuid references public.profiles(id) on delete set null,
  customer_name  text,
  phone          text,
  address        text not null,
  items          jsonb not null,           -- [{id,name,price,qty,image_url}]
  subtotal       numeric(10,2) not null,
  shipping       numeric(10,2) not null default 0,
  total          numeric(10,2) not null,
  payment_method text not null default 'cod',
  status         text not null default 'pending'
                 check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  created_at     timestamptz not null default now()
);

create index if not exists idx_products_category on public.products(category);
create index if not exists idx_wishlist_user     on public.wishlist(user_id);
create index if not exists idx_orders_user       on public.orders(user_id);
create index if not exists idx_orders_created    on public.orders(created_at desc);

-- ---------- AUTO-CREATE PROFILE ON SIGN-UP ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, phone)
  values (new.id, new.phone)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- ADMIN HELPER (avoids RLS recursion) ----------
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

-- ---------- PLACE ORDER (called by the shop at checkout) ----------
-- Prices and stock are checked here on the server, never trusted from the browser.
-- Free delivery above 2000, otherwise 80 (change both numbers here and in config.js).
create or replace function public.place_order(
  p_items   jsonb,
  p_name    text,
  p_phone   text,
  p_address text,
  p_payment text default 'cod'
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  it    jsonb;
  prod  public.products;
  q     integer;
  lines jsonb   := '[]'::jsonb;
  sub   numeric := 0;
  ship  numeric;
  o     public.orders;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if p_address is null or length(trim(p_address)) < 5 then raise exception 'Delivery address is required'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  for it in select * from jsonb_array_elements(p_items) loop
    q := greatest(coalesce((it->>'qty')::int, 1), 1);
    select * into prod from public.products
      where id = (it->>'id')::uuid and status = 'active'
      for update;
    if not found then raise exception 'A product in your cart is no longer available'; end if;
    if prod.stock < q then raise exception 'Only % left of %', prod.stock, prod.name; end if;

    update public.products set stock = stock - q where id = prod.id;
    lines := lines || jsonb_build_object('id', prod.id, 'name', prod.name, 'price', prod.price, 'qty', q, 'image_url', prod.image_url);
    sub := sub + prod.price * q;
  end loop;

  ship := case when sub >= 2000 then 0 else 80 end;

  insert into public.orders (user_id, customer_name, phone, address, items, subtotal, shipping, total, payment_method)
  values (auth.uid(), p_name, p_phone, trim(p_address), lines, sub, ship, sub + ship, coalesce(p_payment, 'cod'))
  returning * into o;

  return o;
end;
$$;

revoke all on function public.place_order(jsonb, text, text, text, text) from public;
grant execute on function public.place_order(jsonb, text, text, text, text) to authenticated;

-- ---------- ROW LEVEL SECURITY ----------
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.wishlist enable row level security;
alter table public.orders   enable row level security;

-- products: shoppers see only active items, the owner sees everything and is the only one who can write
drop policy if exists "products_public_read"  on public.products;
drop policy if exists "products_read"         on public.products;
drop policy if exists "products_admin_insert" on public.products;
drop policy if exists "products_admin_update" on public.products;
drop policy if exists "products_admin_delete" on public.products;

create policy "products_read"         on public.products for select using (status = 'active' or public.is_admin());
create policy "products_admin_insert" on public.products for insert to authenticated with check (public.is_admin());
create policy "products_admin_update" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "products_admin_delete" on public.products for delete to authenticated using (public.is_admin());

-- profiles: a user sees / edits only their own row; the owner can read all (customers list)
drop policy if exists "profiles_select_own"   on public.profiles;
drop policy if exists "profiles_insert_own"   on public.profiles;
drop policy if exists "profiles_update_own"   on public.profiles;
drop policy if exists "profiles_admin_select" on public.profiles;

create policy "profiles_select_own"   on public.profiles for select to authenticated using (auth.uid() = id);
create policy "profiles_admin_select" on public.profiles for select to authenticated using (public.is_admin());
create policy "profiles_insert_own"   on public.profiles for insert to authenticated with check (auth.uid() = id and is_admin = false);
create policy "profiles_update_own"   on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- users may never change is_admin themselves (column-level privilege)
revoke update on public.profiles from authenticated;
grant  update (name, phone, address) on public.profiles to authenticated;

-- wishlist: private to the owner of the row
drop policy if exists "wishlist_select_own" on public.wishlist;
drop policy if exists "wishlist_insert_own" on public.wishlist;
drop policy if exists "wishlist_delete_own" on public.wishlist;

create policy "wishlist_select_own" on public.wishlist for select to authenticated using (auth.uid() = user_id);
create policy "wishlist_insert_own" on public.wishlist for insert to authenticated with check (auth.uid() = user_id);
create policy "wishlist_delete_own" on public.wishlist for delete to authenticated using (auth.uid() = user_id);

-- orders: customers read their own; only place_order() creates them; only the owner updates status
drop policy if exists "orders_select"       on public.orders;
drop policy if exists "orders_admin_update" on public.orders;

create policy "orders_select"       on public.orders for select to authenticated using (auth.uid() = user_id or public.is_admin());
create policy "orders_admin_update" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());

